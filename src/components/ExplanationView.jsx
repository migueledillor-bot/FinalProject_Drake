import React, { useState, useEffect } from 'react';
import { 
  Sparkles, Check, Copy, Download, Lightbulb, ListOrdered, 
  Cpu, Zap, Send, MessageSquare, AlertCircle, BookOpen
} from 'lucide-react';
import { askFollowUpQuestion } from '../services/gemini';

export default function ExplanationView({
  explanation,
  isLoading,
  error,
  code,
  apiKey,
  onOpenApiKeyModal
}) {
  const [copied, setCopied] = useState(false);
  const [followUpQuestion, setFollowUpQuestion] = useState('');
  const [followUpChat, setFollowUpChat] = useState([]);
  const [isFollowUpLoading, setIsFollowUpLoading] = useState(false);
  const [loadingStep, setLoadingStep] = useState(0);

  // Animated loading step ticker
  useEffect(() => {
    if (!isLoading) {
      setLoadingStep(0);
      return;
    }
    const interval = setInterval(() => {
      setLoadingStep((prev) => (prev + 1) % 3);
    }, 900);
    return () => clearInterval(interval);
  }, [isLoading]);

  const loadingMessages = [
    'Scanning code syntax & language...',
    'Translating logic into plain English...',
    'Calculating algorithmic complexity...'
  ];

  // Copy full explanation to clipboard
  const handleCopy = () => {
    if (!explanation) return;
    const text = `
# ${explanation.title} (${explanation.language})

## Plain English Summary
${explanation.summary}

## Step-by-Step Breakdown
${explanation.steps.map(s => `${s.step}. ${s.title}\n${s.explanation}`).join('\n\n')}

## Complexity
- Time: ${explanation.complexity?.time}
- Space: ${explanation.complexity?.space}
- Analysis: ${explanation.complexity?.analysis}

## Key Concepts
${explanation.keyConcepts?.join(', ')}
    `.trim();

    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  // Export as Markdown .md file
  const handleExportMarkdown = () => {
    if (!explanation) return;
    const content = `# ${explanation.title}
**Language:** ${explanation.language}
**Generated by:** DevPlain AI

---

## 💡 Overview in Plain English
${explanation.summary}

## 📋 Step-by-Step Breakdown
${explanation.steps.map(s => `### ${s.step}. ${s.title}\n${s.explanation}\n${s.codeHighlight ? `\`\`\`\n${s.codeHighlight}\n\`\`\`` : ''}`).join('\n\n')}

## ⚡ Algorithmic Complexity
- **Time Complexity:** \`${explanation.complexity?.time}\`
- **Space Complexity:** \`${explanation.complexity?.space}\`
- **Analysis:** ${explanation.complexity?.analysis}

## 🔑 Key Concepts
${explanation.keyConcepts?.map(c => `- ${c}`).join('\n')}

## 💡 Pro Tips & Insights
${explanation.proTips?.map(t => `- ${t}`).join('\n')}
    `;

    const blob = new Blob([content], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${explanation.title.toLowerCase().replace(/[^a-z0-9]/g, '_')}_explanation.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  // Handle follow up chat submit
  const handleSendFollowUp = async (e) => {
    e.preventDefault();
    if (!followUpQuestion.trim() || isFollowUpLoading) return;

    const userQ = followUpQuestion.trim();
    setFollowUpQuestion('');
    setFollowUpChat(prev => [...prev, { sender: 'user', text: userQ }]);
    setIsFollowUpLoading(true);

    try {
      const aiAnswer = await askFollowUpQuestion({
        code,
        previousExplanation: explanation,
        question: userQ,
        apiKey
      });
      setFollowUpChat(prev => [...prev, { sender: 'ai', text: aiAnswer }]);
    } catch (err) {
      setFollowUpChat(prev => [
        ...prev, 
        { sender: 'ai', text: `⚠️ Error: ${err.message || 'Could not process follow-up.'}` }
      ]);
    } finally {
      setIsFollowUpLoading(false);
    }
  };

  // 1. Loading State
  if (isLoading) {
    return (
      <div className="flex flex-col h-full bg-white dark:bg-dark-card rounded-2xl border border-slate-300 dark:border-dark-border p-6 shadow-md dark:shadow-none justify-center items-center text-center space-y-4 min-h-0">
        <div className="relative">
          <div className="w-12 h-12 rounded-2xl bg-gradient-to-tr from-brand-600 to-indigo-500 flex items-center justify-center text-white shadow-lg shadow-brand-500/30 animate-bounce">
            <Sparkles className="w-6 h-6" />
          </div>
          <div className="absolute -inset-1 rounded-2xl bg-brand-500/20 blur-sm animate-pulse" />
        </div>
        <div>
          <h3 className="text-sm font-bold text-slate-900 dark:text-white">
            Explaining Code
          </h3>
          <p className="text-xs font-semibold text-brand-600 dark:text-brand-400 mt-1 h-4">
            {loadingMessages[loadingStep]}
          </p>
        </div>
        <div className="w-full max-w-xs space-y-2 pt-2">
          <div className="h-3 bg-slate-200 dark:bg-dark-surface rounded-full animate-pulse w-3/4 mx-auto" />
          <div className="h-3 bg-slate-200 dark:bg-dark-surface rounded-full animate-pulse w-5/6 mx-auto" />
          <div className="h-3 bg-slate-200 dark:bg-dark-surface rounded-full animate-pulse w-2/3 mx-auto" />
        </div>
      </div>
    );
  }

  // 2. Error State
  if (error) {
    return (
      <div className="flex flex-col h-full bg-white dark:bg-dark-card rounded-2xl border border-rose-300 dark:border-rose-900/60 p-6 shadow-md dark:shadow-none justify-center items-center text-center space-y-3 min-h-0">
        <div className="w-10 h-10 rounded-xl bg-rose-50 dark:bg-rose-950/60 flex items-center justify-center text-rose-600">
          <AlertCircle className="w-5 h-5" />
        </div>
        <div>
          <h3 className="text-sm font-bold text-slate-900 dark:text-white">
            Explanation Failed
          </h3>
          <p className="text-xs text-rose-600 dark:text-rose-400 mt-1 max-w-sm break-words whitespace-pre-line leading-relaxed font-medium">
            {error === 'MISSING_API_KEY'
              ? 'Please provide your Google Gemini API key to start explaining code.'
              : error === 'INVALID_API_KEY'
              ? 'The Gemini API key provided is invalid. Please double-check your key in settings.'
              : error === 'RATE_LIMIT_EXCEEDED'
              ? 'Free tier quota limit reached. Please wait a minute and try again.'
              : error}
          </p>
        </div>
        <button
          onClick={onOpenApiKeyModal}
          className="px-4 py-2 rounded-xl bg-brand-600 hover:bg-brand-500 text-white text-xs font-semibold shadow-md shadow-brand-500/25 transition-all"
        >
          Update API Key
        </button>
      </div>
    );
  }

  // 3. Clean, Uncluttered Empty State
  if (!explanation) {
    return (
      <div className="flex flex-col h-full bg-white dark:bg-dark-card rounded-2xl border border-slate-300 dark:border-dark-border p-6 shadow-md dark:shadow-none justify-center items-center text-center min-h-0">
        <div className="w-12 h-12 rounded-2xl bg-brand-50 dark:bg-brand-950/60 border border-brand-200 dark:border-brand-900/60 flex items-center justify-center text-brand-600 dark:text-brand-400 mb-3">
          <BookOpen className="w-6 h-6" />
        </div>
        <h3 className="text-base font-extrabold text-slate-900 dark:text-white">
          No Code Analyzed Yet
        </h3>
        <p className="text-xs text-slate-500 dark:text-slate-400 mt-1 max-w-xs leading-relaxed">
          Paste your code on the left and click <strong>"Explain Code"</strong> to see a step-by-step breakdown.
        </p>
      </div>
    );
  }

  // 4. Streamlined Explanation View (Full-height scrollable document)
  return (
    <div className="flex flex-col h-full bg-white dark:bg-dark-card rounded-2xl border border-slate-300 dark:border-dark-border shadow-md dark:shadow-none overflow-hidden min-h-0">
      
      {/* Explanation Header */}
      <div className="px-4 py-2.5 border-b border-slate-200 dark:border-dark-border bg-slate-100/80 dark:bg-dark-surface/60 flex items-center justify-between gap-2 shrink-0">
        <div className="flex items-center gap-2 truncate">
          <h2 className="text-xs sm:text-sm font-bold text-slate-900 dark:text-white truncate">
            {explanation.title}
          </h2>
          <span className="px-2 py-0.5 rounded text-[10px] font-mono font-bold bg-brand-100 dark:bg-brand-950 text-brand-700 dark:text-brand-300 shrink-0">
            {explanation.language}
          </span>
        </div>

        {/* Toolbar Buttons */}
        <div className="flex items-center gap-1.5 text-xs font-medium shrink-0">
          <button
            onClick={handleCopy}
            className="flex items-center gap-1 px-2.5 py-1 rounded-lg border border-slate-300 dark:border-dark-border bg-white dark:bg-dark-card hover:bg-slate-50 text-slate-700 dark:text-slate-300 transition-colors shadow-sm"
          >
            {copied ? <Check className="w-3 h-3 text-emerald-600" /> : <Copy className="w-3 h-3" />}
            <span className="hidden sm:inline">{copied ? 'Copied' : 'Copy'}</span>
          </button>
          <button
            onClick={handleExportMarkdown}
            className="flex items-center gap-1 px-2.5 py-1 rounded-lg border border-slate-300 dark:border-dark-border bg-white dark:bg-dark-card hover:bg-slate-50 text-slate-700 dark:text-slate-300 transition-colors shadow-sm"
          >
            <Download className="w-3 h-3" />
            <span className="hidden sm:inline">Export</span>
          </button>
        </div>
      </div>

      {/* Explanation Content (Scrollable) */}
      <div className="flex-1 overflow-y-auto p-4 sm:p-5 space-y-4 min-h-0">
        
        {/* 1. Summary Card */}
        <div className="p-3.5 rounded-xl bg-brand-50/70 dark:bg-brand-950/40 border border-brand-200/80 dark:border-brand-800/40">
          <div className="flex items-center gap-1.5 text-brand-700 dark:text-brand-300 text-xs font-bold uppercase tracking-wider mb-1">
            <Lightbulb className="w-3.5 h-3.5" />
            <span>Plain English Summary</span>
          </div>
          <p className="text-xs sm:text-sm font-medium leading-relaxed text-slate-800 dark:text-slate-200">
            {explanation.summary}
          </p>
        </div>

        {/* 2. Step-by-Step List */}
        <div>
          <div className="flex items-center gap-1.5 text-xs font-bold text-slate-700 dark:text-slate-300 uppercase tracking-wider mb-2.5">
            <ListOrdered className="w-3.5 h-3.5 text-brand-600 dark:text-brand-400" />
            <span>Execution Steps</span>
          </div>
          <div className="space-y-2.5">
            {explanation.steps?.map((stepItem) => (
              <div 
                key={stepItem.step} 
                className="p-3 rounded-xl border border-slate-200 dark:border-dark-border bg-slate-50/60 dark:bg-dark-surface/30 flex gap-3 text-xs"
              >
                <div className="w-5 h-5 rounded-lg bg-brand-600 text-white font-bold text-[11px] flex items-center justify-center shrink-0">
                  {stepItem.step}
                </div>
                <div className="flex-1">
                  <div className="font-bold text-slate-900 dark:text-white">
                    {stepItem.title}
                  </div>
                  <p className="text-slate-600 dark:text-slate-300 mt-0.5 leading-relaxed">
                    {stepItem.explanation}
                  </p>
                  {stepItem.codeHighlight && (
                    <div className="mt-1.5 p-1.5 rounded-lg bg-white dark:bg-dark-bg border border-slate-200 dark:border-dark-border font-mono text-[11px] text-brand-700 dark:text-brand-300 overflow-x-auto">
                      <code>{stepItem.codeHighlight}</code>
                    </div>
                  )}
                </div>
              </div>
            ))}
          </div>
        </div>

        {/* 3. Complexity & Concepts (Compact row) */}
        {explanation.complexity && (
          <div className="p-3 rounded-xl border border-slate-200 dark:border-dark-border bg-slate-50/60 dark:bg-dark-surface/30 flex flex-wrap items-center justify-between gap-2 text-xs">
            <div className="flex items-center gap-3">
              <div>
                <span className="text-[10px] text-slate-400 font-bold uppercase block">Time</span>
                <span className="font-mono font-bold text-brand-600 dark:text-brand-400">
                  {explanation.complexity.time || 'N/A'}
                </span>
              </div>
              <div>
                <span className="text-[10px] text-slate-400 font-bold uppercase block">Space</span>
                <span className="font-mono font-bold text-indigo-600 dark:text-indigo-400">
                  {explanation.complexity.space || 'N/A'}
                </span>
              </div>
            </div>
            {explanation.keyConcepts && explanation.keyConcepts.length > 0 && (
              <div className="flex flex-wrap gap-1">
                {explanation.keyConcepts.map((concept, i) => (
                  <span 
                    key={i} 
                    className="px-2 py-0.5 rounded-md text-[10px] font-semibold bg-white dark:bg-dark-card border border-slate-200 dark:border-dark-border text-slate-700 dark:text-slate-300"
                  >
                    {concept}
                  </span>
                ))}
              </div>
            )}
          </div>
        )}

        {/* 4. Tips */}
        {explanation.proTips && explanation.proTips.length > 0 && (
          <div className="p-3 rounded-xl border border-slate-200 dark:border-dark-border bg-slate-50/60 dark:bg-dark-surface/30 text-xs">
            <div className="flex items-center gap-1 text-slate-700 dark:text-slate-300 font-bold mb-1">
              <Zap className="w-3.5 h-3.5 text-amber-500" />
              <span>Pro Tip</span>
            </div>
            <p className="text-slate-600 dark:text-slate-300 leading-relaxed">
              {explanation.proTips[0]}
            </p>
          </div>
        )}

        {/* Follow-up chat thread */}
        {followUpChat.length > 0 && (
          <div className="space-y-2 pt-2 border-t border-slate-200 dark:border-dark-border">
            {followUpChat.map((msg, i) => (
              <div
                key={i}
                className={`p-2.5 rounded-xl text-xs leading-relaxed ${
                  msg.sender === 'user'
                    ? 'bg-brand-50 dark:bg-brand-950/60 border border-brand-200 dark:border-brand-800 text-brand-950 dark:text-brand-200 ml-4'
                    : 'bg-slate-100 dark:bg-dark-surface border border-slate-200 dark:border-dark-border text-slate-800 dark:text-slate-200 mr-4 whitespace-pre-wrap'
                }`}
              >
                <div className="font-bold text-[9px] text-slate-400 mb-0.5 uppercase">
                  {msg.sender === 'user' ? 'You' : 'Gemini AI'}
                </div>
                <div>{msg.text}</div>
              </div>
            ))}
          </div>
        )}

      </div>

      {/* Pinned Bottom Follow-Up Box */}
      <div className="p-2.5 border-t border-slate-200 dark:border-dark-border bg-slate-100/80 dark:bg-dark-surface/60 shrink-0">
        <form onSubmit={handleSendFollowUp} className="flex gap-2">
          <input
            type="text"
            placeholder="Ask a follow-up about this code..."
            value={followUpQuestion}
            onChange={(e) => setFollowUpQuestion(e.target.value)}
            disabled={isFollowUpLoading}
            className="flex-1 px-3 py-1.5 text-xs rounded-xl border border-slate-300 dark:border-dark-border bg-white dark:bg-dark-surface text-slate-900 dark:text-slate-100 focus:outline-none focus:ring-1 focus:ring-brand-500 disabled:opacity-50"
          />
          <button
            type="submit"
            disabled={isFollowUpLoading || !followUpQuestion.trim()}
            className="px-3 py-1.5 rounded-xl bg-brand-600 hover:bg-brand-500 text-white text-xs font-semibold flex items-center gap-1 transition-all shadow-sm disabled:opacity-40"
          >
            {isFollowUpLoading ? (
              <div className="w-3 h-3 border-2 border-white/30 border-t-white rounded-full animate-spin" />
            ) : (
              <Send className="w-3 h-3" />
            )}
          </button>
        </form>
      </div>

    </div>
  );
}
